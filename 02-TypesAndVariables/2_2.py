# 1. 3 * 2 + 1
# Operators: 2 (*, +)
# Arguments: 3 (3, 2, 1)
# Result: 7
print(3 * 2 + 1)

# 2. 5 + 10 * 5
# Operators: 2 (+, *)
# Arguments: 3 (5, 10, 5)
# Result: 55
print(5 + 10 * 5)

# 3. 4 + 4 / 2 ** 2
# Operators: 3 (+, /, **)
# Arguments: 4 (4, 4, 2, 2)
# Result: 5.0
print(4 + 4 / 2 ** 2)

# 4. 4 % 3 % 2 % 1
# Operators: 3 (%, %, %)
# Arguments: 4 (4, 3, 2, 1)
# Result: 0
print(4 % 3 % 2 % 1)

# 5. 1 + 2 % 3 ** 4 * 5
# Operators: 4 (+, %, **, *)
# Arguments: 5 (1, 2, 3, 4, 5)
# Result: 11
print(1 + 2 % 3 ** 4 * 5)

# 6. True != False
# Operators: 1 (!=)
# Arguments: 2 (True, False)
# Result: True
print(True != False)